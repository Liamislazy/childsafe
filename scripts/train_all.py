"""Tasks 4-6: train every model on the group split and the random split, then tabulate.

    python scripts/train_all.py                  # all models x {group, random}
    python scripts/train_all.py --summary-only   # just rebuild the table from existing runs
"""
import argparse
import json
from pathlib import Path

from childsafe.classifier import train
from childsafe.config import load_config


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary-only", action="store_true")
    ap.add_argument("--models", nargs="*")
    ap.add_argument("--splits", nargs="*", default=["group", "random"])
    ap.add_argument("--robust", action="store_true")
    ap.add_argument("--config", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    models = args.models or cfg["train"]["models"]
    runs = Path(cfg["paths"]["outputs"]) / "runs"

    if not args.summary_only:
        for arch in models:
            for split in args.splits:
                train.main(["--arch", arch, "--split", split] + (["--robust"] if args.robust else [])
                           + (["--config", args.config] if args.config else []))

    rows = ["| model | split | acc | macro-F1 | unsafe recall | unsafe precision | ECE raw | ECE cal | T |",
            "|---|---|---|---|---|---|---|---|---|"]
    for f in sorted(runs.glob("*/metrics.json")):
        m = json.loads(f.read_text())
        t = m["test"]
        rows.append(f"| {m['arch']}{' +A5' if m['robust'] else ''} | {m['split']} | {t['accuracy']:.4f} | "
                    f"{t['macro_f1']:.4f} | {t['binary']['unsafe_recall']:.4f} | {t['binary']['unsafe_precision']:.4f} | "
                    f"{t['ece_raw']:.4f} | {t['ece_calibrated']:.4f} | {t['temperature']:.2f} |")
    text = ("# Module A results (test split)\n\nGenerated by scripts/train_all.py. The random-split rows can be inflated by "
            "near-duplicates shared between train and test; the gap to the group-split rows estimates that leakage.\n\n"
            + "\n".join(rows) + "\n")
    Path(cfg["paths"]["docs"]).mkdir(parents=True, exist_ok=True)
    (Path(cfg["paths"]["docs"]) / "results_moduleA.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
